//=============================================================================
// sobel_edge.v
//-----------------------------------------------------------------------------
// 功能：基于 3x3 窗口做 Sobel 边缘检测
//
// Sobel 卷积核：
//            -1  0  +1          -1  -2  -1
//      Gx =  -2  0  +2    Gy =   0   0   0
//            -1  0  +1          +1  +2  +1
//
//   Gx = (p02 + 2*p12 + p22) - (p00 + 2*p10 + p20)     水平梯度
//   Gy = (p20 + 2*p21 + p22) - (p00 + 2*p01 + p02)     垂直梯度
//
// 梯度幅值：本模块用 |Gx| + |Gy| 近似欧氏幅值 sqrt(Gx²+Gy²)
//   - 优点：不需要乘法器和开方，纯加法，资源极省
//   - 代价：幅值最大高估 √2 倍，对「阈值判边」没有影响（阈值相应调即可）
//   - 若需要精确欧氏幅值，可自行把 mag_sum 改成 Gx*Gx+Gy*Gy 再比较
//
// 输出：
//   o_mag   8 位梯度幅值（= (|Gx|+|Gy|) >> 3，最大 255），可直接当灰度图显示
//   o_edge  二值边缘（mag_sum > THRESH），适合后续统计/二值化
//
// 流水：2 级，输出比输入延迟 2 拍
//
// 适用：紫光同创 Logos2 系列，纯 Verilog-2001，无厂商原语
//=============================================================================
`timescale 1ns / 1ps
`default_nettype none

module sobel_edge #(
    parameter DW     = 8,        // 像素位宽（灰度=8）
    parameter THRESH = 13'd256   // 二值边缘阈值，范围 0~2040
)(
    input  wire            i_clk,
    input  wire            i_rstn,
    input  wire            i_valid,
    input  wire [DW-1:0]   i_p00, i_p01, i_p02,
    input  wire [DW-1:0]   i_p10, i_p11, i_p12,
    input  wire [DW-1:0]   i_p20, i_p21, i_p22,

    output reg             o_valid,
    output reg  [7:0]      o_mag,
    output reg             o_edge
);

    //------------------------------------------------------------------
    // 零扩展到 12 位，保证加减不溢出
    //   单项最大 255，加权后最大 255+510+255 = 1020（11 位）
    //------------------------------------------------------------------
    wire [11:0] x_p02 = {4'b0000, i_p02};
    wire [11:0] x_p12 = {4'b0000, i_p12};
    wire [11:0] x_p22 = {4'b0000, i_p22};
    wire [11:0] x_p00 = {4'b0000, i_p00};
    wire [11:0] x_p10 = {4'b0000, i_p10};
    wire [11:0] x_p20 = {4'b0000, i_p20};
    wire [11:0] x_p01 = {4'b0000, i_p01};
    wire [11:0] x_p21 = {4'b0000, i_p21};

    //------------------------------------------------------------------
    // Gx / Gy 计算（13 位有符号）
    //------------------------------------------------------------------
    wire [11:0] gx_pos = x_p02 + (x_p12 << 1) + x_p22;
    wire [11:0] gx_neg = x_p00 + (x_p10 << 1) + x_p20;
    wire [11:0] gy_pos = x_p20 + (x_p21 << 1) + x_p22;
    wire [11:0] gy_neg = x_p00 + (x_p01 << 1) + x_p02;

    wire signed [12:0] gx = {1'b0, gx_pos} - {1'b0, gx_neg};
    wire signed [12:0] gy = {1'b0, gy_pos} - {1'b0, gy_neg};

    //------------------------------------------------------------------
    // 取绝对值
    //------------------------------------------------------------------
    wire [12:0] gx_a = gx[12] ? (~gx + 13'd1) : gx[12:0];
    wire [12:0] gy_a = gy[12] ? (~gy + 13'd1) : gy[12:0];

    //------------------------------------------------------------------
    // 第 1 级流水：绝对值和
    //------------------------------------------------------------------
    wire [13:0] mag_sum = {1'b0, gx_a} + {1'b0, gy_a};   // 最大 2040

    reg [13:0] s1_mag;
    reg        s1_valid;

    always @(posedge i_clk) begin
        if (!i_rstn) begin
            s1_mag   <= 14'd0;
            s1_valid <= 1'b0;
        end else begin
            s1_mag   <= mag_sum;
            s1_valid <= i_valid;
        end
    end

    //------------------------------------------------------------------
    // 第 2 级流水：输出幅值 + 阈值判边
    //------------------------------------------------------------------
    always @(posedge i_clk) begin
        if (!i_rstn) begin
            o_mag   <= 8'd0;
            o_edge  <= 1'b0;
            o_valid <= 1'b0;
        end else begin
            // 右移 3 位做饱和映射：2040>>3 = 255，正好铺满 8 位
            o_mag   <= s1_mag[10:3];
            o_edge  <= (s1_mag > THRESH);
            o_valid <= s1_valid;
        end
    end

endmodule

`default_nettype wire
