//=============================================================================
// gaussian_3x3.v
//-----------------------------------------------------------------------------
// 功能：3x3 高斯平滑（去噪）
//
// 卷积核（权重和 = 16，所以最后右移 4 位）：
//
//      1  2  1
//      2  4  2
//      1  2  1
//
//   out = ( p00 + 2*p01 + p02
//         + 2*p10 + 4*p11 + 2*p12
//         +   p20 + 2*p21 + p22 ) >> 4
//
// 为什么用这个核：
//   - 权重和是 2 的幂（16），右移 4 位即可，不需要除法器
//   - 系数只有 1/2/4，全部用移位加法实现，不消耗 DSP
//   - 这是最经典的高斯近似，去噪效果和资源开销平衡得很好
//
// 资源：约 9 个加法器 + 1 个移位，无乘法器
// 流水：2 级，输出比输入延迟 2 拍
//
// 适用：紫光同创 Logos2 系列，纯 Verilog-2001，无厂商原语
//=============================================================================
`timescale 1ns / 1ps
`default_nettype none

module gaussian_3x3 #(
    parameter DW = 8
)(
    input  wire            i_clk,
    input  wire            i_rstn,
    input  wire            i_valid,
    input  wire [DW-1:0]   i_p00, i_p01, i_p02,
    input  wire [DW-1:0]   i_p10, i_p11, i_p12,
    input  wire [DW-1:0]   i_p20, i_p21, i_p22,

    output reg             o_valid,
    output reg  [DW-1:0]   o_data
);

    //------------------------------------------------------------------
    // 零扩展到 12 位
    //   加权和最大 = 16*255 = 4080（12 位）
    //------------------------------------------------------------------
    wire [11:0] x00 = {4'b0000, i_p00};
    wire [11:0] x01 = {4'b0000, i_p01};
    wire [11:0] x02 = {4'b0000, i_p02};
    wire [11:0] x10 = {4'b0000, i_p10};
    wire [11:0] x11 = {4'b0000, i_p11};
    wire [11:0] x12 = {4'b0000, i_p12};
    wire [11:0] x20 = {4'b0000, i_p20};
    wire [11:0] x21 = {4'b0000, i_p21};
    wire [11:0] x22 = {4'b0000, i_p22};

    //------------------------------------------------------------------
    // 第 1 级：按行求和（权重 1,2,1）
    //------------------------------------------------------------------
    wire [12:0] row0 = {1'b0, x00} + {x01, 1'b0} + {1'b0, x02};
    wire [12:0] row1 = {1'b0, x10} + {x11, 1'b0} + {1'b0, x12};
    wire [12:0] row2 = {1'b0, x20} + {x21, 1'b0} + {1'b0, x22};

    reg [12:0] s1_row0, s1_row1, s1_row2;
    reg        s1_valid;

    always @(posedge i_clk) begin
        if (!i_rstn) begin
            s1_row0  <= 13'd0;
            s1_row1  <= 13'd0;
            s1_row2  <= 13'd0;
            s1_valid <= 1'b0;
        end else begin
            s1_row0  <= row0;
            s1_row1  <= row1;
            s1_row2  <= row2;
            s1_valid <= i_valid;
        end
    end

    //------------------------------------------------------------------
    // 第 2 级：纵向加权（1,2,1）+ 右移 4 位
    //   总最大 = 16*255 = 4080，>>4 = 255
    //------------------------------------------------------------------
    wire [14:0] total = {2'b00, s1_row0} + {s1_row1, 1'b0} + {2'b00, s1_row2};

    always @(posedge i_clk) begin
        if (!i_rstn) begin
            o_data  <= {DW{1'b0}};
            o_valid <= 1'b0;
        end else begin
            o_data  <= total[11:4];      // >> 4
            o_valid <= s1_valid;
        end
    end

endmodule

`default_nettype wire
