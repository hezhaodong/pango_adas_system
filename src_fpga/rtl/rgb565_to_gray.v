//=============================================================================
// rgb565_to_gray.v
//-----------------------------------------------------------------------------
// 功能：RGB565（16 位）→ 8 位灰度
//
// 公式：Y = (77*R + 150*G + 29*B) >> 8
//      这是 ITU-R BT.601 的整数近似（原式 0.299R + 0.587G + 0.114B）
//      系数和 = 256，所以最后右移 8 位
//
// 实现要点：
//   1) RGB565 → 8bit 用「位复制」扩展，比左移补零更准确
//      R(5bit) → {R, R[4:2]}   例：5'b11111 → 8'b11111111 = 255
//      G(6bit) → {G, G[5:4]}
//      B(5bit) → {B, B[4:2]}
//   2) 乘法用移位加法实现，不消耗 DSP
//      77  = 64 + 8 + 4 + 1
//      150 = 128 + 16 + 4 + 2
//      29  = 16 + 8 + 4 + 1
//   3) 2 级流水线，输出比输入延迟 2 拍
//
// 适用：紫光同创 Logos2 系列，纯 Verilog-2001，无厂商原语
//=============================================================================
`timescale 1ns / 1ps
`default_nettype none

module rgb565_to_gray (
    input  wire        i_clk,
    input  wire        i_rstn,      // 同步低有效复位
    input  wire        i_de,        // 数据有效（行内有效像素）
    input  wire [15:0] i_rgb565,    // {R[4:0], G[5:0], B[4:0]}

    output reg         o_de,        // 延迟 2 拍的 i_de
    output reg  [7:0]  o_gray       // 灰度值
);

    //------------------------------------------------------------------
    // 位复制扩展：5/6 位 → 8 位
    //------------------------------------------------------------------
    wire [7:0] r8 = {i_rgb565[15:11], i_rgb565[13:11]};   // R5 → R8
    wire [7:0] g8 = {i_rgb565[10:5],  i_rgb565[6:5]};     // G6 → G8
    wire [7:0] b8 = {i_rgb565[4:0],   i_rgb565[2:0]};     // B5 → B8

    //------------------------------------------------------------------
    // 移位加法：77R / 150G / 29B
    //------------------------------------------------------------------
    wire [15:0] w_r = (r8 << 6) + (r8 << 3) + (r8 << 2) + r8;
    wire [15:0] w_g = (g8 << 7) + (g8 << 4) + (g8 << 2) + (g8 << 1);
    wire [15:0] w_b = (b8 << 4) + (b8 << 3) + (b8 << 2) + b8;

    //------------------------------------------------------------------
    // 第 1 级流水：寄存三个乘积
    //------------------------------------------------------------------
    reg [15:0] s1_r, s1_g, s1_b;
    reg        s1_de;

    always @(posedge i_clk) begin
        if (!i_rstn) begin
            s1_r  <= 16'd0;
            s1_g  <= 16'd0;
            s1_b  <= 16'd0;
            s1_de <= 1'b0;
        end else begin
            s1_r  <= w_r;
            s1_g  <= w_g;
            s1_b  <= w_b;
            s1_de <= i_de;
        end
    end

    //------------------------------------------------------------------
    // 第 2 级流水：求和 + 右移 8 位
    //   最大和 = 256*255 = 65280，16 位装得下（< 65536）
    //------------------------------------------------------------------
    wire [16:0] w_total = {1'b0, s1_r} + {1'b0, s1_g} + {1'b0, s1_b};

    always @(posedge i_clk) begin
        if (!i_rstn) begin
            o_gray <= 8'd0;
            o_de   <= 1'b0;
        end else begin
            o_gray <= w_total[15:8];    // >> 8
            o_de   <= s1_de;
        end
    end

endmodule

`default_nettype wire
